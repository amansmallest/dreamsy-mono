#!/usr/bin/env python3
"""Builds the complete Luau definitions for the type checker: format/dreamsy.d.luau with its `--@ENTITY_PROPS`
line replaced by one typed field per catalog prop (format/catalog.json, 2D and dimension-free types).

    gen_defs.py <dreamsy.d.luau> <catalog.json> <out.cpp>
"""
import json
import re
import sys
from pathlib import Path

KIND = {"number": "number", "int": "number", "bool": "boolean", "string": "string", "enum": "string",
        "asset": "string", "vec2": "Vec2", "vec3": "Vec3", "color": "any", "entity": "any"}
LUAU_KEYWORDS = {"and", "break", "do", "else", "elseif", "end", "false", "for", "function", "if", "in", "local", "nil",
                 "not", "or", "repeat", "return", "then", "true", "until", "while", "continue", "export", "type", "typeof"}


def entity_props(catalog: dict, declared: set) -> str:
    types: dict[str, set] = {}
    for tname, t in catalog["entities"].items():
        if t["dimension"] == "3d":
            continue
        for pname, p in t["props"].items():
            types.setdefault(pname, set()).add(KIND[p["type"]["kind"]])
    lines = ["-- catalog props (generated from format/catalog.json)"]
    for name in sorted(types):
        if name in declared or name in LUAU_KEYWORDS or not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", name):
            continue
        kinds = types[name]
        lines.append(f"{name}: {kinds.pop() if len(kinds) == 1 else 'any'}")
    return "\n\t".join(lines)


def main():
    defs_path, catalog_path, out = map(Path, sys.argv[1:4])
    defs = defs_path.read_text()
    catalog = json.loads(catalog_path.read_text())
    marker = re.compile(r"^[ \t]*--@ENTITY_PROPS[ \t]*$", re.M)  # the marker line itself, not mentions of it
    m = marker.search(defs)
    if not m:
        sys.exit("gen_defs: no --@ENTITY_PROPS line in dreamsy.d.luau")
    entity_body = defs[defs.index("declare extern type Entity with"):m.start()]
    declared = set(re.findall(r"^\s*([A-Za-z_][A-Za-z0-9_]*)\s*:", entity_body, re.M))
    full = defs[:m.start()] + "\t" + entity_props(catalog, declared) + defs[m.end():]
    data = full.encode()
    rows = ",\n".join(", ".join(f"0x{b:02x}" for b in data[k:k + 24]) for k in range(0, len(data), 24))
    text = ("// Generated by engine/cmake/gen_defs.py. Do not edit.\n#include <string_view>\n\n"
            "namespace dreamsy::check::data {\nnamespace {\n"
            f"const unsigned char kDefs[] = {{\n{rows}, 0x00}};\n}}  // namespace\n"
            f"std::string_view definitions() {{ return {{reinterpret_cast<const char*>(kDefs), {len(data)}}}; }}\n"
            "}  // namespace dreamsy::check::data\n")
    if not out.exists() or out.read_text() != text:
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(text)


if __name__ == "__main__":
    main()
