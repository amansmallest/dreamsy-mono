#!/usr/bin/env python3
"""Generates the embedded Luau sources: the prelude (always linked) and the kit sources (linked only
into tools and tests; players load kits as separate packs, see cmake/gen_kit_packs.py).

    gen_script_data.py <prelude.ts> <kits_dir> <prelude_out.cpp> <kits_out.cpp>

The prelude's source of truth stays engine-web/core/prelude.ts (the shipping engine) until the C++ engine
reaches parity (DREAMSY.MD §14.8): we take the `PRELUDE` template string, substitute `${OP.NAME}` with the
numbers from the `OP` object and decode the JavaScript template escapes. Kits are every
kits/<kit>/**/*.luau (not `_template`), keyed "kits/<kit>/<path>.luau" like engine-web/core/kits.ts.
"""
import re
import sys
from pathlib import Path


def extract_prelude(ts: str) -> str:
    ops = dict((k, int(v)) for k, v in re.findall(r"\b([A-Z_]+):\s*(\d+)", ts[ts.index("export const OP"):ts.index("} as const")]))
    start = ts.index("export const PRELUDE = /* luau */ `") + len("export const PRELUDE = /* luau */ `")
    # the template ends at the first unescaped backtick
    i, out = start, []
    while True:
        c = ts[i]
        if c == "\\":
            n = ts[i + 1]
            out.append({"n": "\n", "t": "\t", "r": "\r", "`": "`", "$": "$", "\\": "\\", "'": "'", '"': '"', "0": "\0"}.get(n, n))
            i += 2
            continue
        if c == "`":
            break
        if c == "$" and ts[i + 1] == "{":
            end = ts.index("}", i)
            expr = ts[i + 2:end].strip()
            m = re.fullmatch(r"OP\.([A-Z_]+)", expr)
            if not m or m.group(1) not in ops:
                sys.exit(f"gen_script_data: unsupported template expression ${{{expr}}} in prelude.ts")
            out.append(str(ops[m.group(1)]))
            i = end + 1
            continue
        out.append(c)
        i += 1
    return "".join(out)


def cpp_string(name: str, text: str) -> str:
    data = text.encode()
    rows = [", ".join(f"0x{b:02x}" for b in data[k:k + 24]) for k in range(0, len(data), 24)]
    body = ",\n".join(rows) if rows else ""
    return f"const unsigned char {name}[] = {{\n{body}{',' if rows else ''} 0x00}};\n"


def write_if_changed(out: Path, text: str):
    if not out.exists() or out.read_text() != text:
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(text)


def main():
    prelude_ts, kits_dir, prelude_out, kits_out = map(Path, sys.argv[1:5])
    prelude = extract_prelude(prelude_ts.read_text())
    write_if_changed(prelude_out, "\n".join([
        "// Generated by engine/cmake/gen_script_data.py. Do not edit.", '#include "script/script_data.h"', "",
        "namespace dreamsy::script::data {", "namespace {", cpp_string("kPrelude", prelude), "}  // namespace",
        f"std::string_view prelude() {{ return {{reinterpret_cast<const char*>(kPrelude), {len(prelude.encode())}}}; }}",
        "}  // namespace dreamsy::script::data", ""]))

    kits = []
    for p in sorted(kits_dir.rglob("*.luau")):
        rel = p.relative_to(kits_dir).as_posix()
        if rel.startswith("_"):
            continue
        kits.append((f"kits/{rel}", p.read_text()))
    parts = ["// Generated by engine/cmake/gen_script_data.py. Do not edit.", '#include "script/embedded_kits.h"', "",
             "namespace dreamsy::script::data {", "namespace {"]
    for i, (_, text) in enumerate(kits):
        parts.append(cpp_string(f"kKit{i}", text))
    parts.append("const KitSource kKits[] = {")
    for i, (path, text) in enumerate(kits):
        parts.append(f'  {{"{path}", {{reinterpret_cast<const char*>(kKit{i}), {len(text.encode())}}}}},')
    parts.append("};")
    parts.append("}  // namespace")
    parts.append(f"std::span<const KitSource> kit_sources() {{ return {{kKits, {len(kits)}}}; }}")
    parts.append("}  // namespace dreamsy::script::data")
    write_if_changed(kits_out, "\n".join(parts) + "\n")


if __name__ == "__main__":
    main()
