std::optional<std::string_view> kit_source(const std::string& path) {
  auto kits = script::data::kit_sources();
  auto it = std::lower_bound(kits.begin(), kits.end(), path,
                             [](const script::data::KitSource& k, const std::string& p) { return k.path < p; });
  if (it == kits.end() || it->path != path) return std::nullopt;
  return it->source;
}

// Module names are package paths ("scripts/client/x.luau") or kit paths ("kits/core/init.luau").
class Resolver : public Luau::FileResolver {
 public:
  Resolver(const pkg::Package& p, std::vector<std::string> kits) : pkg_(p), kits_(std::move(kits)) {}

  std::optional<Luau::SourceCode> readSource(const Luau::ModuleName& name) override {
    std::optional<std::string_view> text = pkg::starts_with(name, "kits/") ? kit_source(name) : pkg_.files.text(name);
    if (!text) return std::nullopt;
    std::string source(*text);
    // Kits are mostly unannotated; in strict mode Luau infers their parameter types from default values
    // ({1, 10, "max"} -> {number}), narrower than the documented usage, and games calling them get false
    // errors. Kits are analyzed nonstrict, so games are checked only against what kits actually declare.
    if (pkg::starts_with(name, "kits/")) {
      for (size_t at = source.find("--!strict"); at != std::string::npos; at = source.find("--!strict", at + 1)) {
        if (at == 0 || source[at - 1] == '\n') source.replace(at, 9, "--!nonstrict");
      }
    }
    return Luau::SourceCode{std::move(source), Luau::SourceCode::Module};
  }

  std::optional<Luau::ModuleInfo> resolveModule(const Luau::ModuleInfo* context, Luau::AstExpr* expr,
                                                const Luau::TypeCheckLimits&) override {
    auto* str = expr ? expr->as<Luau::AstExprConstantString>() : nullptr;
    if (!context || !str) return std::nullopt;  // computed requires can't be resolved statically
    std::string name(str->value.data, str->value.size);
    auto path = script::resolve_require(context->name, name, kits_, [](const std::string& p) { return kit_source(p).has_value(); });
    if (!path) return std::nullopt;
    return Luau::ModuleInfo{path.value()};
  }

  std::string getHumanReadableModuleName(const Luau::ModuleName& name) const override { return name; }

 private:
  const pkg::Package& pkg_;
  std::vector<std::string> kits_;
};

class Config : public Luau::ConfigResolver {
 public:
  explicit Config(bool strict) {
    config_.mode = strict ? Luau::Mode::Strict : Luau::Mode::Nonstrict;
    config_.enabledLint.warningMask = 0;
    using C = Luau::LintWarning;
    for (C::Code code : {C::Code_GlobalUsedAsLocal, C::Code_BuiltinGlobalWrite, C::Code_UnreachableCode,
                         C::Code_UnknownType, C::Code_ForRange, C::Code_UnbalancedAssignment, C::Code_FormatString,
                         C::Code_TableLiteral, C::Code_UninitializedLocal, C::Code_DuplicateFunction,
                         C::Code_DuplicateCondition, C::Code_MisleadingAndOr, C::Code_IntegerParsing,
                         C::Code_ComparisonPrecedence}) {
      config_.enabledLint.enableWarning(code);
    }
  }
  const Luau::Config& getConfig(const Luau::ModuleName&, const Luau::TypeCheckLimits&) const override { return config_; }

 private:
  Luau::Config config_;
};

// Findings that are warnings even in --!strict scripts, because they rarely fail at runtime.
// "X? could be nil" and "expected X, got X?": the value is optional where it's used. Real games do this
// constantly with entities they know exist (entity("hud").text); the engine raises a clear runtime error
// if one is missing, so these are warnings even in --!strict scripts.
bool maybe_nil_only(const Luau::TypeError& e) {
  if (Luau::get_if<Luau::OptionalValueAccess>(&e.data)) return true;
  // Indexing a value the solver couldn't type (`local list = {}` filled later with table.insert):
  // an inference gap, not a likely runtime failure.
  if (const auto* p = Luau::get_if<Luau::UnknownProperty>(&e.data)) return Luau::toString(p->table) == "unknown";
  if (const auto* m = Luau::get_if<Luau::TypeMismatch>(&e.data)) {
    return Luau::toString(m->givenType) == Luau::toString(m->wantedType) + "?";
  }
  return false;
}

// A type mismatch on an element of a positional list literal ({ 1, 10, "max" }, { "Map", onClick }): the
// old solver types such lists from their first element, so valid mixed lists are flagged. The engine
// accepts them, so these are warnings.
bool in_mixed_list(const Luau::SourceModule* sm, const Luau::TypeError& e) {
  if (!sm || !Luau::get_if<Luau::TypeMismatch>(&e.data)) return false;
  for (Luau::AstNode* node : Luau::findAstAncestryOfPosition(*sm, e.location.begin)) {
    auto* table = node->as<Luau::AstExprTable>();
    if (!table) continue;
    for (const Luau::AstExprTable::Item& item : table->items) {
      if (item.kind == Luau::AstExprTable::Item::Kind::List && item.value->location.encloses(e.location)) return true;
    }
  }
  return false;
}

