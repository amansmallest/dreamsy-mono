// Luau's analyzer reports internal failures (time limits, compiler errors) with C++ exceptions; this
// function is the boundary that turns them into a Result. Engine code itself never throws (§14.2).
Result<Report> check_package(const pkg::Package& package, const Options& options) {
  std::vector<std::string> kits =
      pkg::Catalog::get().expand_kits(package.manifest.kits.value_or(std::vector<std::string>{}));
  Resolver resolver(package, kits);
  Config config(options.strict);
  Luau::FrontendOptions frontend_options;
  frontend_options.runLintChecks = true;
  Luau::Frontend frontend(Luau::SolverMode::Old, &resolver, &config, frontend_options);
  Luau::registerBuiltinGlobals(frontend, frontend.globals);

  Report report;
  try {
    Luau::LoadDefinitionFileResult defs = frontend.loadDefinitionFile(
        frontend.globals, frontend.globals.globalScope, data::definitions(), "@dreamsy", false, false);
    if (!defs.success) {
      std::string why;
      for (const Luau::ParseError& e : defs.parseResult.errors)
        why += "\n  dreamsy.d.luau:" + std::to_string(e.getLocation().begin.line + 1) + ": " + e.getMessage();
      for (const Luau::TypeError& e : defs.module ? defs.module->errors : std::vector<Luau::TypeError>{})
        why += "\n  dreamsy.d.luau:" + std::to_string(e.location.begin.line + 1) + ": " + Luau::toString(e);
      return Error{"the API definitions don't load (a build bug):" + why};
    }
    Luau::freeze(frontend.globals.globalTypes);

    std::set<std::tuple<std::string, int, int, std::string>> seen;
    auto add = [&](const std::string& file, const Luau::Location& loc, std::string severity, std::string kind, std::string message) {
      int line = static_cast<int>(loc.begin.line) + 1, col = static_cast<int>(loc.begin.column) + 1;
      if (!seen.insert({file, line, col, message}).second) return;
      (severity == "error" ? report.errors : report.warnings)++;
      report.issues.push_back({file, line, col, std::move(severity), std::move(kind), std::move(message)});
    };

    for (const std::string& path : package.files.paths("scripts/")) {
      if (!pkg::ends_with(path, ".luau")) continue;
      Luau::CheckResult result = frontend.check(path);
      for (const Luau::TypeError& e : result.errors) {
        if (!pkg::starts_with(e.moduleName, "scripts/")) continue;  // kit internals aren't the game's problem
        const Luau::SourceModule* sm = frontend.getSourceModule(e.moduleName);
        bool strict = options.strict || (sm && sm->mode == Luau::Mode::Strict);
        if (const auto* syntax = Luau::get_if<Luau::SyntaxError>(&e.data)) {
          add(e.moduleName, e.location, "error", "syntax", syntax->message);
        } else {
          bool lenient = maybe_nil_only(e) || in_mixed_list(sm, e);
          add(e.moduleName, e.location, strict && !lenient ? "error" : "warning", "type",
              Luau::toString(e, Luau::TypeErrorToStringOptions{frontend.fileResolver}));
        }
      }
      for (const auto* list : {&result.lintResult.errors, &result.lintResult.warnings}) {
        for (const Luau::LintWarning& w : *list) {
          add(path, w.location, "warning", std::string("lint:") + Luau::LintWarning::getName(w.code), w.text);
        }
      }
    }
  } catch (const std::exception& e) {
    return Error{std::string("type checker failed: ") + e.what()};
  }
  std::sort(report.issues.begin(), report.issues.end(), [](const Issue& a, const Issue& b) {
    return std::tie(a.file, a.line, a.column) < std::tie(b.file, b.line, b.column);
  });
  return report;
}

